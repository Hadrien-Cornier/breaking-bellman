// node exp/tools/mkmeasured.js out1.json [out2.json ...] -> web/measured.js: the numbers the level texts quote, from calibration runs
// (same code path, same seeds 101, 202, 303 as the page). Later files override earlier ones.
const fs = require('fs');
const M = {};
// DROP=fk-,qp- leaves out runs whose names start with these prefixes (runs of an older version of a world)
const drop = (process.env.DROP || '').split(',').filter(Boolean);
for (const f of process.argv.slice(2)) for (const r of JSON.parse(fs.readFileSync(f, 'utf8'))) {
  if (r.error || !r.summary || drop.some((d) => r.name.startsWith(d))) continue;
  const s = r.summary;
  M[r.name] = { final: s.finalReturn, finalSd: s.finalSd, peak: s.peak, collapsed: s.collapsedSeeds, kl: s.kl, ent: s.entropy, zf: s.zeroFrac, std: s.std,
    succ: s.successRate, crash: s.crashRate, dist: s.meanDist, test: s.testReturn, base: s.baseRet, baseDist: s.baseDist, vs: s.vsBase,
    pend: s.pendulumScore, worst: s.worstSeed, left: s.leftRate, over: s.overestimate, real: s.realized, seeds: (r.perSeed || []).slice().sort((a, b) => b - a), sec: r.sec, symptoms: r.symptoms };
}
const src = '// Generated by exp/tools/mkmeasured.js from calibration runs (Simulation). Do not edit by hand.\nwindow.CONTENT.M = ' + JSON.stringify(M) + ';\n';
fs.writeFileSync(__dirname + '/../../web/measured.js', src);
console.log(Object.keys(M).length, 'runs ->', 'web/measured.js');
