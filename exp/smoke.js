require('../src/sim/run.js'); require('../src/sim/autopsy.js');
const RLA = globalThis.RLA;
const [world, partsJson, steps, seeds, knobsJson, hyperJson] = process.argv.slice(2);
const parts = JSON.parse(partsJson), knobs = JSON.parse(knobsJson || '{}'), hyper = JSON.parse(hyperJson || '{}');
const res = [];
const t0 = Date.now();
for (let s = 1; s <= +seeds; s++) res.push(RLA.run({ world, parts, steps: +steps, seed: s * 101, knobs, hyper }));
const a = RLA.autopsy(res);
const fmt = (x) => (typeof x === 'number' ? +x.toFixed(2) : x);
console.log(JSON.stringify(parts), JSON.stringify(knobs), JSON.stringify(hyper), ((Date.now() - t0) / 1000).toFixed(1) + 's');
for (const r of res) console.log(' seed', r.seed, 'evals', r.evals.filter((e,i)=>i%4===3).map((e) => Math.round(e.ret)).join(' '), '| pred-disc', r.evals.slice(-5).map(e=>Math.round(e.pred-e.disc)).join(' '), '| maxQ', Math.round(Math.max(...r.evals.map(e=>e.maxQ))));
console.log(' summary', JSON.stringify(a.summary, (k, v) => fmt(v)));
for (const s of a.symptoms) console.log(' ', s.level, s.label, '-', s.evidence);
