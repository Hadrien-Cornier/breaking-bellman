import assert from 'node:assert/strict';
export async function replayReplan(page) {
  const state = () => page.evaluate(() => BBREPLAN.state());
  const frame = () => page.locator('#replan-stage').innerHTML();
  const initial = await state();
  assert.ok(initial.record);
  const id = initial.record.id;
  assert.ok(await page.locator('#replan-stage, #replan-board, #replan-metrics').evaluateAll((es, id) => es.length === 3 && es.every(e => e.dataset.run === id), id));
  assert.ok(!(await page.locator('body').innerText()).includes(id));
  const exact = JSON.stringify(initial.record);
  await page.locator('#replan-replay').click();
  const zero = await frame();
  await page.locator('#replan-step').click();
  const one = await frame();
  assert.notEqual(zero, one);
  await page.locator('#replan-watch').click();
  await page.waitForFunction(() => BBREPLAN.state().replay.t >= 2);
  if ((await state()).replay.playing) await page.locator('#replan-watch').click();
  const paused = (await state()).replay.t;
  await page.waitForTimeout(160);
  assert.equal((await state()).replay.t, paused);
  await page.locator('#replan-replay').click();
  assert.equal(await frame(), zero);
  await page.locator('#replan-step').click();
  assert.equal(await frame(), one);
  assert.equal(JSON.stringify((await state()).record), exact);
  await page.locator('#replan-time').fill('3');
  const clock = await page.locator('#replan-clock').innerText();
  assert.ok(clock.includes('3 / 4'));
  assert.ok(await page.locator('#replan-frame').innerText().then(s => s.includes('ended: wall at time 2')));
  assert.equal(await page.locator('#replan-board [aria-current="step"]').count(), 3);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.locator('#replan-replay').click();
  await page.locator('#replan-watch').click();
  await page.waitForTimeout(160);
  assert.deepEqual((await state()).replay, { t: 0, playing: false });
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.locator('#replan-schedule').selectOption('zero');
  assert.equal((await state()).stale, true);
  assert.ok(await page.locator('#replan-step').isDisabled());
  await page.locator('#replan-run').click();
  const fresh = await state();
  assert.notEqual(fresh.record.id, id);
  assert.equal(fresh.stale, false);
  assert.equal(fresh.record.metrics.open.trueReturn, fresh.record.metrics.replan.trueReturn);
  assert.equal(fresh.record.data.prior.steps, 0);
  const targets = await page.locator('#replan-scene button, #replan-scene select, #replan-time').evaluateAll(es => es.map(e => ({ id: e.id, width: e.getBoundingClientRect().width, height: e.getBoundingClientRect().height })));
  assert.ok(targets.every(t => t.width >= 44 && t.height >= 44), JSON.stringify(targets));
  return fresh.record;
}
